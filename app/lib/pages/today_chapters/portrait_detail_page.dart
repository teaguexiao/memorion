/// P-31 画像详情·它眼中的你（沿用 Figma v2.4 node 343:17497 的特质卡视觉）。
///
/// 全真数据（2026-07-27 起）：卡片列表来自 `InsightsProvider`（`GET /v1/insights`
/// 涌现式洞察引擎），每张卡 = headline + body + evidence（原话/统计），
/// 「准 / 不准」真实走 `POST /v1/insights/{id}/feedback`。
///
/// 设计稿原有的 MBTI/archetype/标签/固定命中率是 mock——后端洞察引擎刻意不设
/// 卡片类型枚举（话题空间就是用户的人生本身），无这些字段，故：
/// - 顶部大标题改为「最新一条洞察的 headline」，副标用陪伴天数 + 观察窗口
/// - 命中率改由用户反馈实算（无反馈时不显示，不造 83% 这种假数据）
class PortraitDetailPage extends StatefulWidget {
  const PortraitDetailPage({super.key});

  @override
  State<PortraitDetailPage> createState() => _PortraitDetailPageState();
}

class _PortraitDetailPageState extends State<PortraitDetailPage> {
  @override
  void initState() {
    super.initState();
    // 直接进本页（未经「关于我」tab）时也要有数据。
    WidgetsBinding.instance.addPostFrameCallback((_) {
      final ip = context.read<InsightsProvider>();
      if (!ip.isInitialized) ip.loadInsights();
    });
  }

  @override
  Widget build(BuildContext context) {
    return Theme(
      data: ThemeData.light(useMaterial3: false).copyWith(
        scaffoldBackgroundColor: JXB.bgApp,
        colorScheme: const ColorScheme.light(primary: JXB.brandPrimary),
      ),
      child: DefaultTextStyle(
        style: JXB.body,
        child: Scaffold(
          backgroundColor: Colors.transparent,
          body: JxbGradientBackground(
            child: SafeArea(
              child: Column(
                children: [
                  _detailBar(context),
                  Expanded(
                    child: Consumer<InsightsProvider>(
                      builder: (context, ip, _) => _buildBody(context, ip),
                    ),
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }

  Widget _buildBody(BuildContext context, InsightsProvider ip) {
    if (ip.isLoading && ip.insights.isEmpty) {
      // 骨架照抄真实版式：两行大标题 + 一行副标题 + 若干洞察卡，加载完不跳版。
      return MemorionSkeleton(
        child: ListView(
          padding: const EdgeInsets.fromLTRB(16, 8, 16, 28),
          children: [
            const SkeletonLine(widthFactor: 0.85, height: 22),
            const SizedBox(height: 10),
            const SkeletonLine(widthFactor: 0.55, height: 22),
            const SizedBox(height: 14),
            const SkeletonLine(widthFactor: 0.42, height: 12),
            const SizedBox(height: 20),
            for (int i = 0; i < 3; i++) ...[
              const SkeletonBox(height: 148, radius: 28),
              const SizedBox(height: 20),
            ],
          ],
        ),
      );
    }
    if (ip.insights.isEmpty) {
      return _emptyState(context, ip);
    }

    final latest = ip.latest!;
    final hitRate = ip.hitRate;
    final sub = <String>[
      if (latest.companionDays != null)
        revampText(context, en: 'Day ${latest.companionDays}', zh: '第 ${latest.companionDays} 天'),
      if (hitRate != null) revampText(context, en: '$hitRate% accurate', zh: '命中率 $hitRate%'),
      revampText(context, en: '${ip.insights.length} insights', zh: '${ip.insights.length} 条洞察'),
    ].join(' · ');

    return RefreshIndicator(
      color: JXB.brandPrimary,
      onRefresh: ip.refresh,
      child: ListView(
        padding: const EdgeInsets.fromLTRB(16, 8, 16, 28),
        children: [
          // 大标题取最新一条洞察（后端无固定 archetype 字段）
          Text(latest.headline,
              style: const TextStyle(
                  fontFamily: JXB.fontSans,
                  fontSize: 24,
                  height: 1.35,
                  fontWeight: FontWeight.w600,
                  color: JXB.textPrimary)),
          const SizedBox(height: 8),
          Text(sub, style: const TextStyle(fontFamily: JXB.fontSans, fontSize: 13, color: JXB.textSecondary)),
          const SizedBox(height: 20),
          for (final card in ip.insights) ...[
            _insightCard(context, ip, card),
            const SizedBox(height: 20),
          ],
          // 底部 AI 免责（同 P-11 约定）
          Center(
            child: Text(
                revampText(context,
                    en: 'Generated by AI from your conversations — may not be fully accurate.',
                    zh: '内容由 AI 生成，可能存在不准确的情况'),
                style: const TextStyle(fontFamily: JXB.fontSans, fontSize: 12, color: JXB.textPlaceholder)),
          ),
        ],
      ),
    );
  }

  /// 空态：账本为空是正常状态（释放阀在证据不够时什么都不发）。
  Widget _emptyState(BuildContext context, InsightsProvider ip) {
    return Center(
      child: Padding(
        padding: const EdgeInsets.symmetric(horizontal: 32),
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            const Icon(Icons.auto_awesome_outlined, size: 40, color: JXB.textPlaceholder),
            const SizedBox(height: 16),
            Text(
              revampText(context,
                  en: "I'm still getting to know you. Keep talking — when I notice something worth saying, it'll show up here.",
                  zh: '我还在认识你。多聊聊，等我注意到值得说的事，就会出现在这里。'),
              textAlign: TextAlign.center,
              style: const TextStyle(fontFamily: JXB.fontSans, fontSize: 14, height: 1.7, color: JXB.textSecondary),
            ),
            if (kDebugMode) ...[
              const SizedBox(height: 20),
              GestureDetector(
                onTap: ip.isRunningEngine ? null : () => _runEngine(ip),
                behavior: HitTestBehavior.opaque,
                child: Container(
                  height: 40,
                  padding: const EdgeInsets.symmetric(horizontal: 20),
                  alignment: Alignment.center,
                  decoration: BoxDecoration(color: JXB.brandSecondary, borderRadius: BorderRadius.circular(99)),
                  child: Text(ip.isRunningEngine ? '生成中…（约 40s）' : 'DEBUG：立即生成', // i18n-ignore: kDebugMode 内的调试按钮
                      style: const TextStyle(
                          fontFamily: JXB.fontSans, fontSize: 14, fontWeight: FontWeight.w500, color: Colors.white)),
                ),
              ),
            ],
          ],
        ),
      ),
    );
  }

  Future<void> _runEngine(InsightsProvider ip) async {
    final showMessage = UndoDeleteHost.messageSink(context);
    final reason = await ip.runEngine();
    if (!mounted) return;
    // i18n-ignore: 仅 kDebugMode 调试入口可触发
    showMessage(reason == null ? '已生成一条洞察' : '本轮未释放：$reason');
  }

  Widget _detailBar(BuildContext context) {
    return SizedBox(
      height: 68,
      child: Padding(
        padding: const EdgeInsets.symmetric(horizontal: 16),
        child: Row(
          children: [
            _circleBtn(Icons.chevron_left_rounded, () => Navigator.of(context).maybePop()),
            Expanded(
              child: Text(revampText(context, en: 'How It Sees You', zh: '它眼中的你'),
                  textAlign: TextAlign.center,
                  style: const TextStyle(
                      fontFamily: JXB.fontSans, fontSize: 16, fontWeight: FontWeight.w500, color: JXB.textSecondary)),
            ),
            const SizedBox(width: 42),
          ],
        ),
      ),
    );
  }

  Widget _circleBtn(IconData icon, VoidCallback onTap) {
    return GestureDetector(
      onTap: onTap,
      behavior: HitTestBehavior.opaque,
      child: Container(
        width: 42,
        height: 42,
        alignment: Alignment.center,
        decoration: BoxDecoration(color: Colors.white.withValues(alpha: 0.5), shape: BoxShape.circle),
        child: Icon(icon, size: 24, color: JXB.textPrimary),
      ),
    );
  }

  /// 单条洞察卡（沿用设计稿特质卡视觉：标题 + 准/不准 pill + 「我是这么想的」证据框）。
  ///
  /// 准/不准**只在未反馈时出现**；反馈过就收起，只留一个淡角标，避免每次进来都
  /// 像在被要求重新确认。
  Widget _insightCard(BuildContext context, InsightsProvider ip, InsightCard card) {
    final rated = card.feedback != InsightFeedback.none;
    return GestureDetector(
      // 点卡片 → 洞察分享页
      onTap: () => Navigator.of(context).push(
        MaterialPageRoute(builder: (_) => FirstImpressionPage(card: card)),
      ),
      behavior: HitTestBehavior.opaque,
      child: Container(
        width: double.infinity,
        padding: const EdgeInsets.all(14),
        decoration: BoxDecoration(color: JXB.surface, borderRadius: BorderRadius.circular(16)),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Expanded(
                  child: Text(card.headline,
                      style: const TextStyle(
                          fontFamily: JXB.fontSans,
                          fontSize: 16,
                          height: 1.4,
                          fontWeight: FontWeight.w500,
                          color: JXB.textPrimary)),
                ),
                const SizedBox(width: 8),
                if (rated)
                  // 已反馈：只留淡角标，不再要求确认
                  Row(
                    children: [
                      Icon(
                        card.feedback == InsightFeedback.accurate
                            ? Icons.check_circle_rounded
                            : Icons.cancel_rounded,
                        size: 15,
                        color: JXB.textPlaceholder,
                      ),
                      const SizedBox(width: 4),
                      Text(
                        card.feedback == InsightFeedback.accurate
                            ? revampText(context, en: 'Accurate', zh: '说得准')
                            : revampText(context, en: 'Not really', zh: '不太准'),
                        style: const TextStyle(
                            fontFamily: JXB.fontSans, fontSize: 12, color: JXB.textPlaceholder),
                      ),
                    ],
                  )
                else
                  Row(
                    children: [
                      _pill(revampText(context, en: 'Right', zh: '准'),
                          onTap: () => ip.submitFeedback(card.id, InsightFeedback.accurate)),
                      const SizedBox(width: 8),
                      _pill(revampText(context, en: 'Wrong', zh: '不准'),
                          onTap: () => ip.submitFeedback(card.id, InsightFeedback.inaccurate)),
                    ],
                  ),
              ],
            ),
            if (card.body.isNotEmpty) ...[
              const SizedBox(height: 8),
              Text(card.body,
                  style: const TextStyle(fontFamily: JXB.fontSans, fontSize: 13, height: 1.6, color: JXB.textSecondary)),
            ],
            // 深读段：上面那些必须挂得住证据，这一段刻意放松（允许推测动机与情绪）。
            // 所以要单独成段、带标记，明示这是解读而不是记录。
            if (card.depth != null) ...[
              const SizedBox(height: 12),
              _sectionLabel(revampText(context, en: 'And what I make of it', zh: '而我是这么看的')),
              const SizedBox(height: 8),
              Text(card.depth!,
                  style: const TextStyle(
                      fontFamily: JXB.fontSans, fontSize: 13, height: 1.75, color: JXB.textPrimary)),
            ],
            // 原话/统计压到最后：它是脚注性质的取证材料，夹在正文与解读中间会打断阅读。
            // 排版也刻意与正文不同（引用竖线 + 弱化字色 + 日期单独一行）——原话是他自己
            // 说的，正文和深读段是我们写的，混成同一种格式会让人分不清哪句该由谁负责。
            if (card.evidence.isNotEmpty) ...[
              const SizedBox(height: 18),
              _sectionLabel(revampText(context, en: 'What I heard', zh: '我听到的')),
              const SizedBox(height: 10),
              // 点原话 → P-11 章节详情取证（有 conversationId 的才可点）。
              for (final ev in card.evidence) ...[
                EvidenceTapWrap(conversationId: ev.conversationId, child: _quoteBlock(ev)),
                const SizedBox(height: 10),
              ],
            ],
          ],
        ),
      ),
    );
  }

  /// 小节标记：一段短横线 + 一行小字。把「解读」和「取证」从正文里分出来。
  Widget _sectionLabel(String text) {
    return Row(
      children: [
        Container(width: 14, height: 1, color: JXB.border),
        const SizedBox(width: 6),
        Text(text,
            style: const TextStyle(
                fontFamily: JXB.fontSans,
                fontSize: 11,
                fontWeight: FontWeight.w500,
                letterSpacing: 0.3,
                color: JXB.textPlaceholder)),
      ],
    );
  }

  /// 一条证据的引用样式：左侧竖线 + 略弱的字色 + 日期单独一行。
  ///
  /// 日期从正文里拿出来单独放，是因为原话本身常常就带标点，`「…」（2026-08-13）`
  /// 挤在一行读起来像句子的一部分。
  Widget _quoteBlock(InsightEvidence ev) {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.only(left: 10),
      decoration: const BoxDecoration(
        border: Border(left: BorderSide(color: JXB.border, width: 2)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(ev.displayText,
              style: const TextStyle(
                  fontFamily: JXB.fontSans, fontSize: 13, height: 1.55, color: JXB.textSecondary)),
          if (ev.date != null) ...[
            const SizedBox(height: 4),
            Text(ev.date!,
                style: const TextStyle(
                    fontFamily: JXB.fontSans, fontSize: 11, color: JXB.textPlaceholder)),
          ],
        ],
      ),
    );
  }

  /// 未反馈时的「准 / 不准」按钮（反馈后整对收起，故无选中态）。
  Widget _pill(String label, {required VoidCallback onTap}) {
    return GestureDetector(
      onTap: onTap,
      behavior: HitTestBehavior.opaque,
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 6),
        decoration: BoxDecoration(
          color: JXB.surface,
          borderRadius: BorderRadius.circular(99),
          border: Border.all(color: JXB.border, width: 1),
        ),
        child: Text(label,
            style: const TextStyle(
                fontFamily: JXB.fontSans, fontSize: 12, fontWeight: FontWeight.w600, color: JXB.textSecondary)),
      ),
    );
  }
}
